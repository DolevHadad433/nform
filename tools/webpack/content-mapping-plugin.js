/**
 * Webpack plugin to automatically update content mapping files during build process
 * This plugin extracts content mappings from built files and writes them to source files
 */
const path = require('path');
const Path = require('path');
const fs = require('fs');

class ContentMappingPlugin {
    constructor(options = {}) {
        this.options = Object.assign(
            {
                outputDir: '',
                targetFiles: [],
                mappingFileName: 'nform-content-mapping.json'
            },
            options
        );
    }

    apply(compiler) {
        const pluginName = 'ContentMappingPlugin';

        // Hook into the emit phase which runs after all assets have been processed and prepared for output
        compiler.hooks.emit.tapAsync(pluginName, async (compilation, callback) => {
            try {
                console.log(`[${pluginName}] Starting content mapping extraction during emit phase...`);

                const outputPath = compilation.outputOptions.path;
                const assets = compilation.assets;

                console.log(`[${pluginName}] Available assets:`, Object.keys(assets).slice(0, 10), '... (showing first 10)');

                // Check if our mapping file is in the assets
                const mappingAsset = assets[this.options.mappingFileName];
                if (mappingAsset) {
                    console.log(`[${pluginName}] Found mapping asset generated by PebulaDynamicDictionaryWebpackPlugin`);
                } else {
                    console.log(`[${pluginName}] No mapping asset found with name:`, this.options.mappingFileName);
                }

                const contentMappings = await this.extractContentMappingsFromAssets(assets);

                console.log(`[${pluginName}] Extracted ${Object.keys(contentMappings).length} content mappings`);

                // Update target files with extracted mappings
                for (const targetFile of this.options.targetFiles) {
                    await this.updateTargetFile(targetFile, contentMappings);
                }

                // IMPORTANT: Don't modify webpack assets to avoid conflicts with PebulaDynamicDictionaryWebpackPlugin
                // The PebulaDynamicDictionaryWebpackPlugin will handle emitting the main mapping file

                console.log(`[${pluginName}] Content mapping update complete`);
                callback();
            } catch (err) {
                console.error(`[${pluginName}] Error:`, err);
                callback();
            }
        });
    }

    async extractContentMappingsFromAssets(assets) {
        const mappings = {};

        try {
            // Get all asset names and filter for content mapping JSON files
            const assetNames = Object.keys(assets);
            console.log(`[ContentMappingPlugin] All assets:`, assetNames.slice(0, 10), '... (showing first 10)');

            // Filter for content mapping JSON files (exclude the main mapping file)
            // Handle both direct assets (production) and assets under assets/ directory (development)
            const contentFiles = assetNames.filter(assetName =>
                assetName.endsWith('.json') &&
                (assetName.startsWith('pbl-') || assetName.startsWith('assets/pbl-')) &&
                !assetName.endsWith(this.options.mappingFileName)
            );

            console.log(`[ContentMappingPlugin] Found ${contentFiles.length} content files in assets:`, contentFiles);

            for (const assetName of contentFiles) {
                try {
                    // Get the asset and its content
                    const asset = assets[assetName];
                    const content = asset.source();
                    const data = JSON.parse(content);

                    // Extract the example name from filename (remove hash and extension)
                    // Handle both direct path and assets/ prefixed paths  
                    const cleanAssetName = assetName.startsWith('assets/') ? assetName.replace('assets/', '') : assetName;
                    const exampleName = cleanAssetName.replace(/^pbl-/, '').replace(/-[a-f0-9]+\.json$/, '');

                    mappings[exampleName] = {
                        file: assetName,
                        content: data,
                        path: `/${assetName}`
                    };

                    console.log(`[ContentMappingPlugin] Processed content file: ${assetName} -> ${exampleName}`);
                } catch (err) {
                    console.warn(`[ContentMappingPlugin] Failed to process asset ${assetName}:`, err.message);
                }
            }
        } catch (err) {
            console.error(`[ContentMappingPlugin] Error reading webpack assets:`, err.message);
        }

        return mappings;
    }

    async extractContentMappings(outputPath) {
        const mappings = {};

        try {
            // Read all files in the output directory
            const files = fs.readdirSync(outputPath);

            // Filter for content mapping JSON files (exclude the main mapping file)
            const contentFiles = files.filter(file =>
                file.endsWith('.json') &&
                file.startsWith('pbl-') &&
                file !== this.options.mappingFileName
            );

            console.log(`[ContentMappingPlugin] Found ${contentFiles.length} content files`);

            for (const file of contentFiles) {
                try {
                    const filePath = path.join(outputPath, file);
                    const content = fs.readFileSync(filePath, 'utf8');
                    const data = JSON.parse(content);

                    // Extract the example name from filename (remove hash and extension)
                    const exampleName = file.replace(/^pbl-/, '').replace(/-[a-f0-9]+\.json$/, '');

                    mappings[exampleName] = {
                        file: file,
                        content: data,
                        path: `/${file}`
                    };
                } catch (err) {
                    console.warn(`[ContentMappingPlugin] Failed to process ${file}:`, err.message);
                }
            }
        } catch (err) {
            console.error(`[ContentMappingPlugin] Error reading output directory:`, err.message);
        }

        return mappings;
    }

    async updateTargetFile(targetFilePath, contentMappings) {
        try {
            console.log(`[ContentMappingPlugin] Updating target file: ${targetFilePath}`);

            // Check if target file exists, create if it doesn't
            if (!fs.existsSync(targetFilePath)) {
                await this.createTargetFile(targetFilePath, contentMappings);
                return;
            }

            let fileContent = fs.readFileSync(targetFilePath, 'utf8');

            // Generate the mappings code
            const mappingsCode = this.generateMappingsCode(contentMappings);

            // Determine if this is a service file or a core file
            const isServiceFile = targetFilePath.includes('content-map.service.ts');

            if (isServiceFile) {
                // For service files, we need to append the CONTENT_MAPPINGS at the end of the file
                // First, remove any existing CONTENT_MAPPINGS declarations at the end
                fileContent = fileContent.replace(
                    /\/\/\s*Auto-generated.*[\s\S]*?export\s+const\s+CONTENT_MAPPINGS[\s\S]*$/g,
                    ''
                );

                // Clean up trailing whitespace
                fileContent = fileContent.trim();

                // Add the CONTENT_MAPPINGS at the end
                fileContent += `\n\n// Auto-generated content mappings\n\nexport const CONTENT_MAPPINGS = ${mappingsCode};\n`;
            } else {
                // For core files, replace the entire CONTENT_MAPPINGS declaration
                // First, remove all existing CONTENT_MAPPINGS declarations
                fileContent = fileContent.replace(
                    /(export\s+const\s+CONTENT_MAPPINGS\s*=\s*)[^;]+;/g,
                    `$1${mappingsCode};`
                );

                // If no CONTENT_MAPPINGS found, add it with a header
                if (!fileContent.includes('CONTENT_MAPPINGS')) {
                    fileContent = `// Auto-generated content mappings file\n\nexport const CONTENT_MAPPINGS = ${mappingsCode};\n`;
                }
            }

            fs.writeFileSync(targetFilePath, fileContent);
            console.log(`[ContentMappingPlugin] Successfully updated ${targetFilePath}`);
        } catch (err) {
            console.error(`[ContentMappingPlugin] Error updating ${targetFilePath}:`, err.message);
        }
    }

    async createTargetFile(targetFilePath, contentMappings) {
        const mappingsCode = this.generateMappingsCode(contentMappings);
        const fileContent = `// Auto-generated content mappings file
export const CONTENT_MAPPINGS = ${mappingsCode};
`;

        // Ensure directory exists
        const dir = path.dirname(targetFilePath);
        if (!fs.existsSync(dir)) {
            fs.mkdirSync(dir, { recursive: true });
        }

        fs.writeFileSync(targetFilePath, fileContent);
        console.log(`[ContentMappingPlugin] Created new target file: ${targetFilePath}`);
    }

    generateMappingsCode(contentMappings) {
        const mappingsObj = {};

        for (const [key, mapping] of Object.entries(contentMappings)) {
            mappingsObj[key] = {
                file: mapping.file,
                path: mapping.path,
                hasContent: mapping.content && Object.keys(mapping.content).length > 0
            };
        }

        return JSON.stringify(mappingsObj, null, 2);
    }

    async updateMainMappingFile(outputPath, contentMappings) {
        const mappingFilePath = path.join(outputPath, this.options.mappingFileName);

        try {
            console.log(`[ContentMappingPlugin] Updating mapping file at: ${mappingFilePath}`);

            // Read existing mapping file if it exists (should contain PebulaDynamicDictionaryWebpackPlugin content)
            let existingMapping = {};
            if (fs.existsSync(mappingFilePath)) {
                try {
                    const existingContent = fs.readFileSync(mappingFilePath, 'utf8');
                    console.log(`[ContentMappingPlugin] Found existing mapping content: ${existingContent.substring(0, 200)}...`);
                    existingMapping = JSON.parse(existingContent);
                } catch (err) {
                    console.warn(`[ContentMappingPlugin] Could not parse existing mapping file, creating new one:`, err.message);
                }
            } else {
                console.log(`[ContentMappingPlugin] No existing mapping file found at ${mappingFilePath}`);
            }

            // Create a comprehensive mapping file that merges with existing content
            // Keep all existing properties from PebulaDynamicDictionaryWebpackPlugin (searchContent, markdownPages, markdownCodeExamples)
            const mainMapping = {
                ...existingMapping,
                examples: {},
                metadata: {
                    totalExamples: Object.keys(contentMappings).length,
                    generatedAt: new Date().toISOString(),
                    buildPath: outputPath,
                    hasSearchContent: !!existingMapping.searchContent,
                    hasMarkdownPages: !!existingMapping.markdownPages,
                    hasMarkdownCodeExamples: !!existingMapping.markdownCodeExamples
                }
            };

            // Add our extracted content mappings
            for (const [key, mapping] of Object.entries(contentMappings)) {
                mainMapping.examples[key] = {
                    file: mapping.file,
                    path: mapping.path,
                    contentCount: mapping.content ? (mapping.content.length || Object.keys(mapping.content).length) : 0
                };
            }

            const finalContent = JSON.stringify(mainMapping, null, 2);
            console.log(`[ContentMappingPlugin] Writing merged content with ${Object.keys(mainMapping.examples).length} examples and dynamic content keys: ${Object.keys(existingMapping).join(', ')}`);

            // Ensure directory exists
            const dir = path.dirname(mappingFilePath);
            if (!fs.existsSync(dir)) {
                fs.mkdirSync(dir, { recursive: true });
            }

            fs.writeFileSync(mappingFilePath, finalContent);
            console.log(`[ContentMappingPlugin] Updated main mapping file: ${mappingFilePath}`);
        } catch (err) {
            console.error(`[ContentMappingPlugin] Error updating main mapping file:`, err.message);
        }
    }
}

module.exports = ContentMappingPlugin;
